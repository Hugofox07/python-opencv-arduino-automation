# =========================================================
# OpenCV
# =========================================================

import cv2 as cv

# =========================================================
# YOLO
# =========================================================

from ultralytics import YOLO

# =========================================================
# Serial Arduino
# =========================================================

import serial

# =========================================================
# Tempo
# =========================================================

import time


# =========================================================
# ARDUINO
# =========================================================

arduino = serial.Serial(
    'COM4',
    9600
)

time.sleep(2)

# =========================================================
# SERVO
# =========================================================

angulo_servo = 90

arduino.write(b'90\n')

time.sleep(1)


# =========================================================
# YOLO
# =========================================================

model = YOLO(
    "yolov8n.pt"
)


# =========================================================
# CÂMERA
# =========================================================

cap = cv.VideoCapture(0)

# =========================================================
# LOOP
# =========================================================

while True:

    ret, frame = cap.read()

    if not ret:
        break


    # =====================================================
    # REDIMENSIONA
    # =====================================================

    frame = cv.resize(
        frame,
        (640,480)
    )

    altura, largura, _ = frame.shape

    centro_tela_x = largura // 2


    # =====================================================
    # YOLO
    # =====================================================

    results = model(
        frame,
        conf=0.5,
        imgsz=320
    )


    # =====================================================
    # RESULTADOS
    # =====================================================

    for r in results:

        boxes = r.boxes

        for box in boxes:

            # =============================================
            # CLASSE
            # =============================================

            classe = int(
                box.cls[0]
            )

            nome = model.names[
                classe
            ]


            # =============================================
            # DETECTA PESSOA
            # =============================================

            if nome == "person":

                # =========================================
                # COORDENADAS
                # =========================================

                x1, y1, x2, y2 = map(
                    int,
                    box.xyxy[0]
                )

                # =========================================
                # CENTRO OBJETO
                # =========================================

                centro_x = (
                    x1 + x2
                ) // 2

                centro_y = (
                    y1 + y2
                ) // 2


                # =========================================
                # DESENHOS
                # =========================================

                cv.rectangle(
                    frame,
                    (x1,y1),
                    (x2,y2),
                    (0,255,0),
                    2
                )

                cv.circle(
                    frame,
                    (centro_x, centro_y),
                    5,
                    (0,0,255),
                    -1
                )


                # =========================================
                # LINHA CENTRO TELA
                # =========================================

                cv.line(
                    frame,
                    (centro_tela_x,0),
                    (centro_tela_x,480),
                    (255,255,255),
                    2
                )


                # =========================================
                # ERRO
                # =========================================

                erro = centro_x - centro_tela_x
                print("ERRO:", erro)


                # =========================================
                # DEAD ZONE
                # =========================================

                if abs(erro) < 10:

                    erro = 0


                # =========================================
                # GANHO
                # =========================================

                ganho = 0.15

                alvo = int(
                    angulo_servo +
                    (erro * ganho)
                )


                # =========================================
                # LIMITES
                # =========================================

                alvo = max(
                    60,
                    min(120, alvo)
                )


                # =========================================
                # SUAVIZAÇÃO
                # =========================================

                velocidade = 3

                if angulo_servo < alvo:

                    angulo_servo += velocidade

                elif angulo_servo > alvo:

                    angulo_servo -= velocidade


                # =========================================
                # SERIAL
                # =========================================

                comando = f"{angulo_servo}\n"

                arduino.write(
                    comando.encode()
                )


                # =========================================
                # TEXTO
                # =========================================

                cv.putText(
                    frame,
                    f'Servo: {angulo_servo}',
                    (20,40),
                    cv.FONT_HERSHEY_SIMPLEX,
                    1,
                    (0,255,255),
                    2
                )

                cv.putText(
                    frame,
                    f'Erro: {erro}',
                    (20,80),
                    cv.FONT_HERSHEY_SIMPLEX,
                    1,
                    (255,255,255),
                    2
                )


    # =====================================================
    # MOSTRA
    # =====================================================

    cv.imshow(
        "YOLO Servo Tracking",
        frame
    )


    # =====================================================
    # SAIR
    # =====================================================

    if cv.waitKey(1) & 0xFF == ord('q'):
        break


# =========================================================
# FECHA
# =========================================================

cap.release()

cv.destroyAllWindows()