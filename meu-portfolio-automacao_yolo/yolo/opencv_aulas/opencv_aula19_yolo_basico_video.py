# =========================================================
# OpenCV
# =========================================================

import cv2 as cv

# =========================================================
# YOLO
# =========================================================

from ultralytics import YOLO

# =========================================================
# Tempo / FPS
# =========================================================

import time 


# =========================================================
# CARREGA MODELO
# =========================================================

model = YOLO(
    "yolov8n.pt"
)

# yolov8n = versão leve e rápida


# =========================================================
# WEBCAM
# =========================================================

#cap = cv.VideoCapture(0)

# Para vídeo:
cap = cv.VideoCapture("sources/estrada3.mp4")
     
 


# =========================================================
# TESTA CÂMERA
# =========================================================

if not cap.isOpened():

    print("Erro webcam")

    exit()


# =========================================================
# FPS
# =========================================================

prev_time = 0


# =========================================================
# LOOP
# =========================================================

while True:

    # =====================================================
    # LÊ FRAME
    # =====================================================

    ret, frame = cap.read()

    if not ret:
        break


    # =====================================================
    # REDIMENSIONA
    # =====================================================

    frame = cv.resize(
        frame,
        (1280, 720)
    )


    # =====================================================
    # YOLO DETECÇÃO
    # =====================================================

    results = model(
        frame,
        conf=0.5
    )


    # =====================================================
    # DESENHA RESULTADOS
    # =====================================================

    annotated_frame = results[0].plot()


    # =====================================================
    # FPS
    # =====================================================

    current_time = time.time()

    fps = 1 / (
        current_time - prev_time
    )

    prev_time = current_time


    # =====================================================
    # TEXTO
    # =====================================================

    cv.putText(
        annotated_frame,
        "YOLOv8 DETECTION",
        (20,40),
        cv.FONT_HERSHEY_SIMPLEX,
        1,
        (0,255,0),
        2
    )

    cv.putText(
        annotated_frame,
        f'FPS: {int(fps)}',
        (20,80),
        cv.FONT_HERSHEY_SIMPLEX,
        1,
        (0,255,255),
        2
    )


    # =====================================================
    # MOSTRA
    # =====================================================

    cv.imshow(
        "YOLOv8 OpenCV",
        annotated_frame
    )


    # =====================================================
    # TECLA SAIR
    # =====================================================

    if cv.waitKey(1) & 0xFF == ord('q'):
        break


# =========================================================
# FECHA
# =========================================================

cap.release()

cv.destroyAllWindows()